// Prints the MCP tool reference (docs/mcp-tools.md) from the live registry so
// the documentation can never drift from the code. `npm run mcp:docs` writes
// it; test/mcp.docs.test.js fails when the committed file is stale.
const { listTools } = require('../src/mcp/tools');

const SCOPE_ORDER = ['health:read', 'health:log', 'health:write', 'family:manage'];
const SCOPE_BLURB = {
  'health:read': 'Read-only. Nothing is changed.',
  'health:log': 'Everyday "log this" actions. Additive and easy to correct.',
  'health:write': 'Edits, uploads and permanent deletes. Deletes are two-step (see the Safety section).',
  'family:manage': 'Summaries across the family profiles an account supports.',
};

// First sentence, not splitting after abbreviations like "e.g." or "vs.".
function firstSentence(text) {
  const re = /([.!?])\s+(?=[A-Z])/g;
  let m;
  while ((m = re.exec(text))) {
    const before = text.slice(0, m.index + 1);
    if (!/(e\.g|i\.e|vs|etc)\.$/i.test(before)) return before;
  }
  return text;
}

function render() {
  const tools = listTools();
  const lines = [
    '# EyeMyHealth MCP tool reference',
    '',
    '_Generated by `npm run mcp:docs` from the live tool registry - do not edit by hand._',
    '',
    `${tools.length} tools. Every tool except \`list_profiles\` and \`get_family_dashboard\` also accepts an optional \`profileId\` (from \`list_profiles\`) to act for a family profile.`,
    '',
  ];
  for (const scope of SCOPE_ORDER) {
    const inScope = tools.filter((t) => t.scope === scope);
    if (inScope.length === 0) continue;
    lines.push(`## \`${scope}\` (${inScope.length})`, '', SCOPE_BLURB[scope], '', '| Tool | What it does | Arguments |', '| --- | --- | --- |');
    for (const t of inScope) {
      const props = Object.keys(t.inputSchema.properties || {});
      const required = new Set(t.inputSchema.required || []);
      const args = props.map((p) => (required.has(p) ? `**${p}**` : p)).join(', ') || '-';
      const kind = t.annotations.destructiveHint ? ' _(permanent, two-step)_' : '';
      const first = firstSentence(t.description).replace(/\|/g, '\\|');
      lines.push(`| \`${t.name}\`${kind} | ${first} | ${args} |`);
    }
    lines.push('');
  }
  lines.push('Bold arguments are required.', '');
  return lines.join('\n');
}

if (require.main === module) process.stdout.write(render());
module.exports = { render };
