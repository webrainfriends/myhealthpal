const deviceService = require('../../services/deviceService');
const { readTool, evidence } = require('./helpers');

const DATE = { type: 'string', description: 'YYYY-MM-DD' };

// ------------------------------------------------------------------- diet

const getDietSummary = readTool({
  name: 'get_diet_summary',
  description: 'Calories and nutrients per day for the last N days (1-90, default 7), grouped by meal, plus how many logged meals still need review.',
  properties: { days: { type: 'integer', minimum: 1, maximum: 90 } },
  async execute(args, { userId }) {
    return { data: await dietReadService.getSummary(userId, args.days), evidence: [] };
  },
});

const listFoodEntries = readTool({
  name: 'list_food_entries',
  description: 'Logged meals/foods with calories and nutrients. Defaults to today; pass `date`, or `from`/`to`, or `unconfirmed: true` for entries awaiting review.',
  properties: { date: DATE, from: DATE, to: DATE, unconfirmed: { type: 'boolean' } },
  async execute(args, { userId }) {
    const entries = await dietReadService.listEntries(userId, {
      date: args.date,
      from: args.from,
      to: args.to,
      unconfirmed: args.unconfirmed === true ? 'true' : undefined,
    });
    return { data: { entries }, evidence: evidence('food_entry', entries, 'id', 'name') };
  },
});

const getDietRecommendations = readTool({
  name: 'get_diet_recommendations',
  description:
    'Pattern analysis of recent eating with practical tips that take the person\'s confirmed lab results and active medicines into account. ' +
    'Generated by AI and cached; needs the person\'s "AI health insights" consent in EyeMyHealth.',
  properties: { days: { type: 'integer', minimum: 3, maximum: 90 } },
  async execute(args, { userId }) {
    const days = Math.min(Math.max(Number.parseInt(args.days, 10) || 14, 3), 90);
    const recommendation = await dietInsightService.getOrGenerateRecommendations(userId, { windowDays: days });
    return { data: { recommendation }, evidence: [] };
  },
});

const listDietSchedules = readTool({
  name: 'list_diet_schedules',
  description: 'Meal plans (diet schedules) the person has created or imported, newest first.',
  async execute(args, { userId }) {
    const schedules = await scheduleService.listSchedules(userId);
    return { data: { schedules }, evidence: evidence('diet_schedule', schedules, 'id', 'title') };
  },
});

const getDietSchedule = readTool({
  name: 'get_diet_schedule',
  description: 'One meal plan with every day\'s meals by id.',
  properties: { scheduleId: { type: 'string' } },
  required: ['scheduleId'],
  async execute(args, { userId }) {
    const schedule = await scheduleService.getScheduleWithEntries(userId, args.scheduleId);
    if (!schedule) return { data: { found: false }, evidence: [] };
    return { data: { found: true, schedule }, evidence: [{ type: 'diet_schedule', id: schedule.id, label: schedule.title }] };
  },
});

